/**
 * Turns the raw sticker renders (Codex image_gen PNGs with alpha, ~1254px square) into web stickers.
 *
 *   npx tsx apps/web/scripts/optimize-stickers.ts <dir-with-pngs>
 *
 * The raw PNGs stay out of the repo (2-3 MB each). Each one is trimmed to its die-cut silhouette,
 * resized so its longer side is 480px (2x the largest display size), and exported as alpha WebP to
 * public/art/stickers/<name>.webp. Also writes src/landing/stickers.ts with the intrinsic sizes,
 * so the page can set width/height and never shift layout while they load.
 */
import { readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const here = dirname(fileURLToPath(import.meta.url));
const webDir = resolve(here, "..");
const outDir = join(webDir, "public", "art", "stickers");
const manifestFile = join(webDir, "src", "landing", "stickers.ts");
const LONG_SIDE = 480;

const src = process.argv[2];
if (!src) throw new Error("usage: optimize-stickers.ts <dir-with-pngs>");

const sizes: Record<string, { w: number; h: number }> = {};
for (const file of readdirSync(src)
  .filter((f) => f.endsWith(".png"))
  .sort()) {
  const name = basename(file, ".png");
  const trimmed = await sharp(join(src, file))
    .ensureAlpha()
    .trim({ threshold: 1 })
    .toBuffer({ resolveWithObject: true });
  const { width, height } = trimmed.info;
  const scale = LONG_SIDE / Math.max(width, height);
  const w = Math.round(width * scale);
  const h = Math.round(height * scale);
  const out = await sharp(trimmed.data)
    .resize(w, h)
    .webp({ quality: 82, alphaQuality: 90, effort: 6 })
    .toFile(join(outDir, `${name}.webp`));
  sizes[name] = { w: w / 2, h: h / 2 };
  console.log(`${name}: ${w}x${h}, ${(out.size / 1024).toFixed(1)} KB`);
}

const body = Object.entries(sizes)
  .map(([k, v]) => `  ${k}: { w: ${v.w}, h: ${v.h} },`)
  .join("\n");
writeFileSync(
  manifestFile,
  `// Generated by scripts/optimize-stickers.ts: 1x intrinsic sizes of public/art/stickers/*.webp.\nexport const STICKERS = {\n${body}\n} as const;\n\nexport type StickerName = keyof typeof STICKERS;\n`,
);
